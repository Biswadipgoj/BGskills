// Generates site/src/data/capabilities.ts from integrations/catalog.json so the
// portfolio site and the planner share one source of truth.

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(process.argv[2] || '.');
const cat = JSON.parse(fs.readFileSync(path.join(ROOT, 'integrations', 'catalog.json'), 'utf8'));

const SECTION_BY_ID = {
  'jev-ultrafast': 'browser', 'browser-use': 'browser', crawlee: 'browser', scrapling: 'browser', 'playwright-test': 'browser',
  motion: 'animation', anime: 'animation', 'animate-css': 'animation', '12-principles-animation': 'animation',
  'codex-security': 'security', 'cloudflare-security-audit': 'security',
  sqlmap: 'pentest', 'awesome-hacking': 'pentest',
  appwrite: 'backend', prisma: 'backend', redis: 'backend', meilisearch: 'backend', clickhouse: 'backend', tidb: 'backend', netdata: 'backend', 'react-native': 'backend', expo: 'backend',
  keploy: 'quality', 'open-code-review': 'quality', superpowers: 'quality', 'mattpocock-skills': 'quality',
  'claude-plugins-official': 'agents', 'awesome-claude-code': 'agents', ruflo: 'agents', paperclip: 'agents', 'agent-reach': 'agents',
  archify: 'planning', 'app-ideas': 'planning',
  'kubernetes-the-hard-way': 'devops', 'awesome-scalability': 'devops', n8n: 'devops',
  impeccable: 'design', bootstrap: 'design', 'font-awesome': 'design', 'css-gg': 'design', 'emil-design-eng': 'design', 'make-interfaces-better': 'design', 'shadcn-ui': 'design',
  'front-end-checklist': 'feedback', 'react-doctor': 'feedback', 'fixing-accessibility': 'feedback',
};

// One list of areas, in display order. Colours are dark enough for AA text on the site's light cards.
const SECTIONS = [
  ['agents', 'Agents & skills', '#4b3aa0'], ['planning', 'Planning', '#3d5a1f'], ['design', 'Design', '#a3401a'],
  ['feedback', 'Design feedback', '#8a5a00'], ['animation', 'Animation', '#6a3f8f'], ['browser', 'Browser', '#0e5f8a'],
  ['backend', 'Backend', '#1f6b3a'], ['quality', 'Quality & testing', '#5b4a10'], ['security', 'Security', '#9b2a1f'],
  ['pentest', 'Penetration testing', '#7a1f3a'], ['devops', 'DevOps', '#0a5f5a'],
];
const ORDER = SECTIONS.map(([k]) => k);
const COLOR = Object.fromEntries(SECTIONS.map(([k, , col]) => [k, col]));
const SECTION_LABEL = Object.fromEntries(SECTIONS.map(([k, l]) => [k, l]));

const entries = cat.entries
  .map((e) => ({
    id: e.id,
    name: e.name,
    section: e.section || SECTION_BY_ID[e.id] || 'quality',
    desc: e.use.length > 130 ? e.use.slice(0, 127).trimEnd() + '...' : e.use,
    required: !!e.required,
    stars: e.stars || null,
    repo: e.repo,
  }))
  .sort((a, b) => {
    const d = ORDER.indexOf(a.section) - ORDER.indexOf(b.section);
    if (d) return d;
    return (b.stars || 0) - (a.stars || 0);
  });

const total = entries.length;
const requiredCount = entries.filter((e) => e.required).length;

const out = `// SPDX-License-Identifier: Apache-2.0
// Copyright (c) 2026 Biswodip Goj
// GENERATED by scripts/generate-site-capabilities.mjs from integrations/catalog.json.
// Do not edit by hand — edit the catalog and re-run: node scripts/generate-site-capabilities.mjs .

export type CapabilitySection = ${ORDER.map((k) => `'${k}'`).join(' | ')};

export interface Capability {
  id: string;
  name: string;
  section: CapabilitySection;
  desc: string;
  required: boolean;
  stars: number | null;
  repo: string;
}

export const CAPABILITY_COLOR: Record<CapabilitySection, string> = ${JSON.stringify(COLOR, null, 2)};

export const CAPABILITY_LABEL: Record<CapabilitySection, string> = ${JSON.stringify(SECTION_LABEL, null, 2)};

export const CAPABILITY_SECTIONS: CapabilitySection[] = ${JSON.stringify(ORDER)};

export const CAPABILITY_TOTAL = ${total};
export const CAPABILITY_REQUIRED = ${requiredCount};

export const CAPABILITIES: Capability[] = ${JSON.stringify(entries, null, 2)};
`;

const outDir = path.join(ROOT, 'site', 'src', 'data');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'capabilities.ts'), out);


// ---- everything else the site shows, read from the repo so the page cannot drift from it ----

// The planner itself: the same file /dip runs, so the site's "try it" box gives the real plan.
const core = fs.readFileSync(path.join(ROOT, 'scripts', 'lib', 'plan-core.mjs'), 'utf8');
fs.writeFileSync(path.join(outDir, 'plan-core.mjs'), `// GENERATED copy of scripts/lib/plan-core.mjs — do not edit; re-run scripts/generate-site-capabilities.mjs.\n${core}`);
// catalogOnly entries only need what the planner reads (they match by name), not their descriptions
const pick = (e) => Object.fromEntries(['id', 'name', 'kind', 'agent', 'platform', 'group', 'priority', 'whenVague', 'fallbackFor', 'lang', 'catalogOnly', ...(e.catalogOnly ? [] : ['use']), 'docs', 'repo']
  .filter((k) => e[k] !== undefined).map((k) => [k, e[k]]).concat([['signals', { keywords: e.signals?.keywords || [] }]]));
fs.writeFileSync(path.join(outDir, 'planner-catalog.json'), JSON.stringify({ agents: cat.agents, entries: cat.entries.map(pick) }, null, 1) + '\n');

const lifecycle = fs.readdirSync(path.join(ROOT, 'lifecycle')).filter((f) => /^\d\d-.*\.md$/.test(f)).sort().map((f) => {
  const md = fs.readFileSync(path.join(ROOT, 'lifecycle', f), 'utf8');
  const title = md.match(/^# (\d\d) — (.+?)(?: \((Phase[^)]*)\))?\s*$/m) || [];
  const gate = md.split(/^## Exit gate\s*$/m)[1] || '';
  return { n: title[1] || f.slice(0, 2), title: title[2] || f, phase: title[3] || '', file: `lifecycle/${f}`,
    gates: [...gate.matchAll(/^- \[ \] (.+)$/gm)].map((m) => m[1].replace(/`/g, '')).slice(0, 3) };
});
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'integrations', 'manifest.json'), 'utf8'));
const upstreams = manifest.integrations.map((i) => ({ id: i.id, name: i.name, repo: i.repo.replace(/\.git$/, ''), license: i.license,
  commit: i.snapshot?.commit || null, version: i.snapshot?.version || null, skills: (i.skills || []).length }));
const cmdDir = path.join(ROOT, 'templates', 'claude', 'commands');
const desc = (file) => (fs.readFileSync(file, 'utf8').match(/^description:\s*(.+)$/m) || [])[1] || '';
const commands = [['/dip', path.join(cmdDir, 'dip.md')], ['/dip-setapi', path.join(cmdDir, 'dip-setapi.md')],
  ...fs.readdirSync(path.join(cmdDir, 'dip')).sort().map((f) => [`/dip:${f.replace(/\.md$/, '')}`, path.join(cmdDir, 'dip', f)])]
  .map(([name, file]) => ({ name, description: desc(file) }));
const agentDir = path.join(ROOT, 'templates', 'claude', 'agents');
const agents = fs.readdirSync(agentDir).sort().map((f) => ({ name: `@${f.replace(/\.md$/, '')}`, description: desc(path.join(agentDir, f)) }));
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
fs.writeFileSync(path.join(outDir, 'repo.json'), JSON.stringify({ version: pkg.version, license: pkg.license, lifecycle, upstreams, commands, agents }, null, 1) + '\n');
console.log(`site/src/data: plan-core.mjs, planner-catalog.json, repo.json (${lifecycle.length} phases, ${upstreams.length} upstreams, ${commands.length} commands)`);


console.log(`site/src/data/capabilities.ts generated — ${total} capabilities (${requiredCount} required)`);
for (const s of ORDER) {
  const list = entries.filter((e) => e.section === s);
  console.log(`  ${s}: ${list.length}`);
}
